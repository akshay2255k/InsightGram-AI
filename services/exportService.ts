import type {
    DashboardStatistics,
    InstagramExport,
    InstagramUser,
} from "../types/instagram";

import { downloadFile } from "../utils/helpers";

function flattenUsers(
    data: InstagramExport
): InstagramUser[] {

    return [

        ...data.followers,

        ...data.following,

        ...data.pendingRequests,

        ...data.recentRequests,

        ...data.recentlyUnfollowed,

        ...data.closeFriends,

    ];

}

export function exportAsJSON(
    data: InstagramExport
): void {

    downloadFile(

        "instagram-export.json",

        JSON.stringify(
            data,
            null,
            2
        ),

        "application/json"

    );

}

export function exportAsCSV(
    data: InstagramExport
): void {

    const users =
        flattenUsers(data);

    const rows = [

        [
            "Username",
            "Profile URL",
            "Follows You",
            "You Follow",
            "Pending",
            "Recent Request",
            "Recently Unfollowed",
            "Close Friend",
        ].join(","),

    ];

    users.forEach((user) => {

        rows.push(

            [

                user.username,

                user.profileUrl,

                user.followsYou,

                user.youFollow,

                user.isPending ?? false,

                user.isRecentRequest ?? false,

                user.isRecentlyUnfollowed ?? false,

                user.isCloseFriend ?? false,

            ].join(",")

        );

    });

    downloadFile(

        "instagram-export.csv",

        rows.join("\n"),

        "text/csv"

    );

}
